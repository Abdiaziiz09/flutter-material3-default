/// Names of the application's routes.
///
/// Always refer to routes through these constants instead of string literals.
abstract final class AppRoutes {
  /// The home route, which shows the adaptive navigation shell.
  static const String home = '/';

  /// Deep-link route that opens the shell directly on the components view.
  static const String components = '/components';

  /// Deep-link route that opens the shell directly on the settings view.
  static const String settings = '/settings';
}
